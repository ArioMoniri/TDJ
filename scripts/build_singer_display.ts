/**
 * QA fix 2026-11: the singers' display names (data/knowledge/singer_display.json), from data/index/singers.json.
 *
 * - `duets`: a duet as the discography spells it ("C. Dante - J. Martel", "Lita Morales - H. Lagos") → each voice in
 *   full, joined with " & " ("Carlos Dante & Julio Martel"): an initial is expanded to the one singer of that surname
 *   and initial who sang with the duet's orchestra (else the one singer in the index), and stays as it is otherwise.
 * - `keys`: a singer's normalised key, when its title case is not its name, (energy.ts normTitle: "alberto podesta", "lita morales h lagos") → the display
 *   name with its accents ("Alberto Podestá", "Lita Morales & Horacio Lagos"), for the lists that store the key.
 *
 * Run: pnpm --filter @tdj/core exec tsx ../../scripts/build_singer_display.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { normTitle } from "../packages/core/src/energy";
import { findRoot } from "../packages/core/src/load";

interface Row {
  id: string;
  name: string;
  count: number;
  orchestras?: Record<string, number>;
}
const root = findRoot();
const rows = JSON.parse(readFileSync(join(root, "data/index/singers.json"), "utf8")) as Row[];
const SPLIT = /\s+-\s+/;
const singles = rows.filter((r) => !SPLIT.test(r.name));
const fold = (s: string) => normTitle(s);
/** what a key reads as without the table (learnedRules' title case): only names that differ are listed */
const titleCase = (s: string) =>
  s.replace(/(^|\s)(\p{L})/gu, (_m, a: string, c: string) => a + c.toUpperCase());

/** "C. Dante" → "Carlos Dante" when exactly one singer fits (the duet's orchestras first) */
function expand(part: string, orchestras: string[]): string {
  const m = /^((?:[A-ZÁÉÍÓÚÑ]\.\s*)+)(.+)$/u.exec(part.trim());
  if (!m) return part.trim();
  const initials = m[1]!.replace(/\s+/g, "").split(".").filter(Boolean);
  const surname = fold(m[2]!);
  const fits = singles.filter((r) => {
    const w = r.name.split(/\s+/);
    if (w.length < 2) return false;
    if (fold(w.slice(initials.length).join(" ")) !== surname) return false;
    return initials.every((c, k) => fold(w[k] ?? "").startsWith(fold(c)));
  });
  const withOrch = fits.filter((r) => orchestras.some((o) => r.orchestras?.[o]));
  const pick = withOrch.length === 1 ? withOrch[0] : fits.length === 1 ? fits[0] : undefined;
  return pick ? pick.name : part.trim();
}

const duets: Record<string, string> = {};
const keys: Record<string, string> = {};
for (const r of rows) {
  if (SPLIT.test(r.name)) {
    const orch = Object.keys(r.orchestras ?? {});
    const parts = r.name.split(SPLIT).map((p) => expand(p, orch));
    const display =
      parts.length > 2 ? `${parts.slice(0, -1).join(", ")} & ${parts.at(-1)}` : parts.join(" & ");
    duets[r.name] = display;
    keys[fold(r.name)] = display;
  } else if (titleCase(fold(r.name)) !== r.name) keys[fold(r.name)] = r.name;
}
const out = {
  note: "Generated by scripts/build_singer_display.ts from data/index/singers.json: duets in full, normalised keys → display names.",
  duets: Object.fromEntries(Object.entries(duets).sort()),
  keys: Object.fromEntries(Object.entries(keys).sort()),
};
writeFileSync(join(root, "data/knowledge/singer_display.json"), `${JSON.stringify(out, null, 1)}\n`);
console.log(`${Object.keys(duets).length} duets, ${Object.keys(keys).length} keys`);
