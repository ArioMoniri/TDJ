/**
 * Wave 4 — outlines for the generated night covers (src/lib/cover). The cover is an SVG string drawn the same in a
 * browser canvas, in the apps' web views and in resvg on the server, so its words cannot depend on the fonts a
 * machine has: every letter is a path from this table. Run after changing the character set or the fonts:
 *   pnpm --filter @tdj/web exec tsx scripts/cover-glyphs.ts
 * Fonts: Fraunces 600 (the night's title, as the DMG art and the app's headings) and Inter 600 (the small lines),
 * from @fontsource (OFL), the Latin and Latin Extended subsets (Turkish ğ ı İ ş live in the second).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const file = (pkg: string, name: string) =>
  join(dirname(require.resolve(`${pkg}/package.json`)), "files", name);
const load = (p: string) => {
  const b = readFileSync(p);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};

const chars = new Set<string>();
const range = (a: number, b: number) => {
  for (let c = a; c <= b; c++) chars.add(String.fromCodePoint(c));
};
range(0x20, 0x7e);
range(0xa0, 0xff);
// Turkish first, then the letters of the other European names a night is called after (Łódź, Šibenik, Kraków)
for (const c of "ĞğİıŞşŒœŁłŠšŽžČčĆćĘęŃńŚśŹźŻżŘřĚěŮůŐőŰűĀāĒēĪīŌōŪū–—‘’“”…•·′″€") chars.add(c);

/** units per em in the table: 1/500 em is a quarter pixel on a 64 px title */
const UNITS = 500;
const r = (n: number) => Math.round(n);
function table(fonts: opentype.Font[]) {
  const glyphs: Record<string, [number, string]> = {};
  const picked = new Map<string, { font: opentype.Font; g: opentype.Glyph }>();
  for (const ch of chars) {
    for (const font of fonts) {
      const g = font.charToGlyph(ch);
      if (!g || g.index === 0) continue;
      const s = UNITS / font.unitsPerEm;
      // opentype.js already flips y (SVG's y down) when it builds a path at a size
      const path = g.getPath(0, 0, UNITS);
      // relative commands from the pen (the shortest numbers); opentype's zero-length line after a move is dropped
      let px = 0;
      let py = 0;
      let start = { x: 0, y: 0 };
      const pair = (x: number, y: number) => `${x}${y < 0 ? "" : " "}${y}`;
      let d = "";
      for (const c of path.commands) {
        if (c.type === "Z") {
          d += "z";
          px = start.x;
          py = start.y;
          continue;
        }
        const x = r(c.x);
        const y = r(c.y);
        if (c.type === "M") {
          d += `m${pair(x - px, y - py)}`;
          start = { x, y };
        } else if (c.type === "L") {
          if (x === px && y === py) continue;
          d += `l${pair(x - px, y - py)}`;
        } else if (c.type === "Q") d += `q${pair(r(c.x1) - px, r(c.y1) - py)} ${pair(x - px, y - py)}`;
        else
          d += `c${pair(r(c.x1) - px, r(c.y1) - py)} ${pair(r(c.x2) - px, r(c.y2) - py)} ${pair(x - px, y - py)}`;
        px = x;
        py = y;
      }
      d = d.replace(/ -/g, "-");
      glyphs[ch] = [r((g.advanceWidth ?? 0) * s), d];
      picked.set(ch, { font, g });
      break;
    }
  }
  // kerning between the letters a title is made of (ASCII and Turkish), the pairs worth a visible nudge
  const kern: Record<string, number> = {};
  const kc = [...picked.keys()].filter((c) => /[A-Za-z0-9.,ğışçöüĞİŞÇÖÜ'’-]/.test(c));
  for (const a of kc)
    for (const b of kc) {
      const A = picked.get(a)!;
      const B = picked.get(b)!;
      if (A.font !== B.font) continue;
      const v = r(A.font.getKerningValue(A.g, B.g) * (UNITS / A.font.unitsPerEm));
      if (Math.abs(v) >= 15) kern[a + b] = v;
    }
  const f = fonts[0]!;
  const s = UNITS / f.unitsPerEm;
  return {
    ascent: r(f.ascender * s),
    descent: r(-f.descender * s),
    cap: r(((f.tables.os2 as { sCapHeight?: number } | undefined)?.sCapHeight ?? 700) * s),
    glyphs,
    kern,
  };
}

const serif = table([
  load(file("@fontsource/fraunces", "fraunces-latin-600-normal.woff")),
  load(file("@fontsource/fraunces", "fraunces-latin-ext-600-normal.woff")),
]);
const sans = table([
  load(file("@fontsource/inter", "inter-latin-600-normal.woff")),
  load(file("@fontsource/inter", "inter-latin-ext-600-normal.woff")),
]);

const out = `/* Generated by scripts/cover-glyphs.ts — do not edit. Fraunces 600 and Inter 600 (SIL Open Font License 1.1),
   outlined at 500 units per em as relative paths, y down, origin on the baseline. */
export interface GlyphFont {
  ascent: number;
  descent: number;
  cap: number;
  /** character → [advance, path] */
  glyphs: Record<string, [number, string]>;
  /** pair → kerning */
  kern: Record<string, number>;
}
export const SERIF: GlyphFont = ${JSON.stringify(serif)};
export const SANS: GlyphFont = ${JSON.stringify(sans)};
`;
writeFileSync(join(here, "../src/lib/cover/glyphs.ts"), out);
console.log(
  `glyphs.ts: ${Object.keys(serif.glyphs).length} serif + ${Object.keys(sans.glyphs).length} sans glyphs, ${
    Object.keys(serif.kern).length + Object.keys(sans.kern).length
  } kerning pairs, ${(out.length / 1024).toFixed(0)} KB`,
);
