// The server routes the standalone apps run unchanged on the device. The app build (apps/desktop/scripts/build-ui.mjs)
// copies each route file into the bundle with its server modules pointed at device ones (src/lib/app/server/*), and
// writes src/lib/app/deviceRoutes.ts over those copies. A route that imports anything else server-side fails here,
// in the app build and in src/lib/app/deviceRoutes.test.ts, instead of shipping a server module in the app.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** URL path → route folder under src/app/api */
export const DEVICE_ROUTES = {
  "/api/ai/review": "ai/review",
  "/api/ai/refine": "ai/refine",
  "/api/ai/swap": "ai/swap",
  "/api/ai/edit": "ai/edit",
  "/api/song-search": "song-search",
  "/api/add-side": "add-side",
  "/api/build": "build",
  "/api/fill": "fill",
};

/** server module → its device counterpart */
export const SWAPS = {
  "next/server": "@/lib/app/server/next",
  "@/lib/server/llm": "@/lib/app/server/llm",
  "@/lib/server/catalog": "@/lib/app/server/catalog",
  "@/lib/server/guard": "@/lib/app/server/guard",
};

/** imports that are the same plain modules on the device */
const CLIENT_SAFE = [
  /^@tdj\/core$/,
  /^@\/lib\/ai\//,
  /^@\/lib\/(feedback|build|songWire|fill\/sources)$/,
  /^@\/lib\/server\/wire$/,
];

const IMPORT = /(\bfrom\s+|\bimport\s+)(["'])([^"']+)\2/g;

/** the route's source with its server imports swapped; throws on an import the device has no counterpart for */
export function deviceSource(src, name = "route") {
  return src.replace(IMPORT, (all, kw, q, spec) => {
    if (spec in SWAPS) return `${kw}${q}${SWAPS[spec]}${q}`;
    if (CLIENT_SAFE.some((r) => r.test(spec))) return all;
    throw new Error(
      `${name} imports ${spec}, which has no device counterpart: add one under src/lib/app/server and to SWAPS in apps/web/scripts/device-routes.mjs`,
    );
  });
}

/** the named imports a route takes from each swapped server module (the device module must export them all) */
export function swappedNames(src) {
  const out = {};
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*["']([^"']+)["']/g)) {
    if (!(m[2] in SWAPS)) continue;
    const names = m[1]
      .split(",")
      .map((s) => s.trim().replace(/^type\s+/, ""))
      .filter(Boolean)
      .map((s) => s.split(/\s+as\s+/)[0]);
    out[m[2]] = [...(out[m[2]] ?? []), ...names];
  }
  return out;
}

export const slug = (dir) => dir.replace(/\//g, "-");

/**
 * Writes the device copies to <outDir>/device-routes/<slug>.ts from <webSrc>/app/api/<dir>/route.ts, and
 * <outDir>/deviceRoutes.ts that maps each URL path to its handlers. The app build writes them over src/lib/app of
 * its copy of apps/web; the tests to src/lib/app/__device__. Returns the files written.
 */
export function writeDeviceRoutes(webSrc, outDir) {
  const dir = join(outDir, "device-routes");
  mkdirSync(dir, { recursive: true });
  const written = [];
  for (const route of Object.values(DEVICE_ROUTES)) {
    const src = readFileSync(join(webSrc, "app", "api", route, "route.ts"), "utf8");
    const file = join(dir, `${slug(route)}.ts`);
    writeFileSync(
      file,
      `// generated by apps/web/scripts/device-routes.mjs from src/app/api/${route}/route.ts\n${deviceSource(src, route)}`,
    );
    written.push(file);
  }
  const entries = Object.entries(DEVICE_ROUTES);
  const index = [
    "// generated by apps/web/scripts/device-routes.mjs: the server routes the app runs on the device",
    ...entries.map(([, r], i) => `import * as r${i} from "./device-routes/${slug(r)}";`),
    "type H = (req: Request) => Promise<Response>;",
    'export const DEVICE_ROUTES: Record<string, Partial<Record<"GET" | "POST", H>>> = {',
    ...entries.map(([path], i) => `  ${JSON.stringify(path)}: r${i} as Partial<Record<"GET" | "POST", H>>,`),
    "};",
    "",
  ].join("\n");
  const indexFile = join(outDir, "deviceRoutes.ts");
  writeFileSync(indexFile, index);
  written.push(indexFile);
  return written;
}
